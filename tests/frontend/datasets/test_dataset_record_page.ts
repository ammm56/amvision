import Button from '../../../frontend/web-ui/src/shared/ui/components/Button.vue'

const api = vi.hoisted(() => ({ getDatasetImportDetail: vi.fn(), getDatasetExportDetail: vi.fn(), getDatasetInfo: vi.fn(), getDatasetWorkspace: vi.fn(), deleteDatasetImport: vi.fn(), apiRequest: vi.fn() }))
const route = reactive({ params: { datasetImportId: 'import-a', datasetExportId: '' } })
vi.mock('../../../frontend/web-ui/src/modules/datasets/services/dataset.service', () => api)
vi.mock('../../../frontend/web-ui/src/modules/datasets/services/dataset-workspace.service', () => api)
