export function useDatasetText() {
  const { locale } = useI18n()
  return (key: string) => {
    const entry = Object.hasOwn(labels, key)
      ? labels[key as keyof typeof labels]
      : undefined
    return entry ? entry[locale.value.startsWith('zh') ? 0 : 1] : key
  }
}
export function datasetError(error: unknown) {
  return error instanceof Error ? error.message : String(error)
}
export function datasetDate(value?: string | null) {
  if (!value) return '—'
  const date = new Date(value)
  return Number.isNaN(date.valueOf())
    ? '—'
    : date.toLocaleString(undefined, {
        year: 'numeric',
        month: '2-digit',
        day: '2-digit',
        hour: '2-digit',
        minute: '2-digit',
        hour12: false,
      })
}
