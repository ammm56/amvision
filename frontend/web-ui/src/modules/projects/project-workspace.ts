export function useProjectText() {
  const { locale } = useI18n()
  return (key: keyof typeof labels) => labels[key][Math.max(0, ['zh-CN', 'en-US', 'ja-JP', 'ko-KR'].indexOf(locale.value))]
}
export function projectName(project: ProjectCatalogItem): string { return project.display_name || project.project_id }
export function projectDate(value?: string | null): string {
  if (!value) return '—'
  const date = new Date(value)
  if (!Number.isFinite(date.getTime())) return '—'
  const two = (number: number) => String(number).padStart(2, '0')
  return `${date.getFullYear()}-${two(date.getMonth() + 1)}-${two(date.getDate())} ${two(date.getHours())}:${two(date.getMinutes())}`
}
export function projectError(error: unknown): string { return error instanceof Error ? error.message : String(error) }
